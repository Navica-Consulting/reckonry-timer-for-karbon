#!/usr/bin/env bash
# Builds two packages from src/:
#   dist/reckonry-timer-for-karbon-<ver>.zip        store build, app2.karbonhq.com (publish this one)
#   dist/reckonry-timer-for-karbon-<ver>-stage.zip  stage build, webapp-stage.karbonhq.com (never publish)
set -euo pipefail
cd "$(dirname "$0")"
VER=$(python3 -c "import json;print(json.load(open('src/manifest.json'))['version'])")
rm -rf dist && mkdir -p dist

build() { # target origin nameSuffix
  local target=$1 origin=$2 suffix=$3 out=dist/$1
  cp -r src "$out"
  printf "// Build target: %s. Generated by build.sh.\n// eslint-disable-next-line no-unused-vars\nconst KT_ORIGIN = '%s';\n" "$target" "$origin" > "$out/config.js"
  python3 - "$out/manifest.json" "$origin" "$suffix" <<'PY'
import json, sys
path, origin, suffix = sys.argv[1], sys.argv[2], sys.argv[3]
m = json.load(open(path))
pattern = origin + '*'
m['host_permissions'] = [pattern]
for cs in m['content_scripts']:
    cs['matches'] = [pattern]
if suffix:
    m['name'] = 'Reckonry Timer for Karbon (stage)'
    m['action']['default_title'] = 'Reckonry Timer for Karbon (stage)'
json.dump(m, open(path, 'w'), indent=2)
PY
  local zip=dist/reckonry-timer-for-karbon-$VER${suffix}.zip
  (cd "$out" && zip -qr "../$(basename "$zip")" . -x '.*')
  echo "Built $zip"
}

build store https://app2.karbonhq.com/ ""
build stage https://webapp-stage.karbonhq.com/ "-stage"
