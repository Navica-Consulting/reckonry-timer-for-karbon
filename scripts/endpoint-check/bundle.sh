#!/usr/bin/env bash
# Builds out/run.js: src/karbon.js plus check.js, run with the options in config.local.json.
# Paste out/run.js into a signed-in Karbon tab (javascript_tool, or DevTools). It returns the report.
#   ./bundle.sh            reads and writes (blank timer cycle, plus a saved minute if a test client is set)
#   ./bundle.sh --read     reads only
#   ./bundle.sh --src      tests src/ as it is now (for a fix), instead of the latest release tag
set -euo pipefail
cd "$(dirname "$0")"
ROOT=../..
CFG=config.local.json
[ -f "$CFG" ] || echo '{ "writes": true, "client": null }' > "$CFG"
OPTS=$(python3 -c "import json,sys;o=json.load(open('$CFG'));o['writes']=o.get('writes',True) and '--read' not in sys.argv[1:];print(json.dumps(o))" "$@")
mkdir -p out
# By default, test what users run: karbon.js at the newest v* tag.
if [[ " $* " == *" --src "* ]]; then KARBON=$(cat "$ROOT/src/karbon.js"); REF=src
else REF=$(git -C "$ROOT" tag -l 'v*' --sort=-v:refname | head -1); KARBON=$(git -C "$ROOT" show "$REF:src/karbon.js"); fi
{
  echo "// Generated by scripts/endpoint-check/bundle.sh. Do not edit."
  echo "await (async () => {"
  printf '%s\n' "$KARBON"
  cat check.js
  echo "return KTCheck(KTKarbon, $OPTS);"
  echo "})();"
} > out/run.full.js
# Compacting would change a template literal that spans lines, so refuse one.
if awk '{ if (gsub(/`/, "`") % 2) bad = 1 } END { exit !bad }' out/run.full.js; then echo "A template literal spans lines; compaction is unsafe." >&2; exit 1; fi
# Comment lines and indentation dropped, so the paste is about half the size. No template literal spans lines.
python3 -c "import sys;print('\\n'.join(l.strip() for l in open(sys.argv[1]) if l.strip() and not l.strip().startswith('//')))" out/run.full.js > out/run.js
node --check out/run.js 2>/dev/null || node -e "new (Object.getPrototypeOf(async function(){}).constructor)(require('fs').readFileSync('out/run.js','utf8'))"
echo "Wrote scripts/endpoint-check/out/run.js ($(wc -c < out/run.js) bytes, karbon.js from $REF, writes: $(python3 -c "import json;print(json.loads('''$OPTS''')['writes'])"))"
